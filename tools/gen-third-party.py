#!/usr/bin/env python3
"""Gradle's resolved graph -> third-party/jvm/{BUCK,classpaths.bzl}.

Input: build/deps/<project>.json, written by tools/dumpdeps.init.gradle.kts -- one entry per
resolvable configuration with the nodes gradle selected, the edges between them and the
artifacts it put on the classpath, each with a sha256.

Output:
  BUCK            one remote_jar per distinct artifact (coordinate + classifier), url + sha256.
                  This file is the lockfile; its diff after `just lock` is the review.
  classpaths.bzl  CLASSPATHS[project][configuration] = [labels...], in gradle's order, external
                  artifacts only. Project-to-project edges are written by hand in each BUCK
                  file, because they are the part of the graph that is not mechanical.

Gradle resolves each configuration independently, and they disagree (the annotation-processor
classpath carries guava 32 while compile carries 33.6); that is why targets are keyed by exact
version rather than by module, and why classpaths are per configuration.
"""
import json
import pathlib
import re
import sys

REPOS = {
    "MavenRepo": "https://repo.maven.apache.org/maven2/",
    "maven": "https://repo.papermc.io/repository/maven-public/",
}
CONFIGURATIONS = ["compileClasspath", "annotationProcessor", "runtimeClasspath", "testRuntimeClasspath"]


def target_name(group, module, version, classifier):
    raw = "__".join(x for x in (group, module, version, classifier) if x)
    return re.sub(r"[^A-Za-z0-9._-]", "_", raw)


def main(deps_dir, out_dir):
    deps_dir, out_dir = pathlib.Path(deps_dir), pathlib.Path(out_dir)
    jars = {}      # name -> (url, sha256, coordinate)
    classpaths = {}
    for f in sorted(deps_dir.glob("*.json")):
        project = f.stem
        data = json.loads(f.read_text())
        classpaths[project] = {}
        for conf in CONFIGURATIONS:
            if conf not in data:
                continue
            nodes = data[conf]["nodes"]
            labels = []
            for a in data[conf]["artifacts"]:
                node = nodes[a["component"]]
                if node["kind"] != "module":
                    continue
                if not a["sha256"]:
                    sys.exit(f"{project}/{conf}: {a['file']} is not a file")
                group, module, version = node["group"], node["module"], node["version"]
                file_version = version
                if node.get("timestamp"):
                    file_version = version.replace("SNAPSHOT", node["timestamp"])
                fname = a["file"]
                stem = f"{module}-{version}"
                if not fname.startswith(stem):
                    sys.exit(f"{project}/{conf}: cannot split classifier off {fname} (expected prefix {stem})")
                rest = fname[len(stem):]              # "-linux-x86_64.jar" or ".jar"
                ext = rest.rsplit(".", 1)[1]
                classifier = rest[1:-len(ext) - 1] if rest.startswith("-") else ""
                remote_name = f"{module}-{file_version}" + (f"-{classifier}" if classifier else "") + f".{ext}"
                repo = node.get("repository")
                if repo not in REPOS:
                    sys.exit(f"{project}/{conf}: {a['component']} resolved from unknown repository {repo!r}")
                url = REPOS[repo] + f"{group.replace('.', '/')}/{module}/{version}/{remote_name}"
                name = target_name(group, module, version, classifier)
                coordinate = f"{group}:{module}:{version}" + (f":{classifier}" if classifier else "")
                prev = jars.get(name)
                if prev and prev[1] != a["sha256"]:
                    sys.exit(f"{name}: sha256 differs between configurations ({prev[1]} vs {a['sha256']})")
                jars[name] = (url, a["sha256"], coordinate)
                label = f"//third-party/jvm:{name}"
                if label not in labels:
                    labels.append(label)
            classpaths[project][conf] = labels

    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "BUCK").open("w") as w:
        w.write("# GENERATED by tools/gen-third-party.py via `just lock` -- do not edit.\n")
        w.write("# One target per artifact gradle resolved, keyed by exact version; this is the lockfile.\n\n")
        w.write('load("@jvm//rules:java.bzl", "remote_jar")\n\n')
        for name in sorted(jars):
            url, sha, coordinate = jars[name]
            w.write(f"# {coordinate}\nremote_jar(\n    name = \"{name}\",\n    url = \"{url}\",\n    sha256 = \"{sha}\",\n    visibility = [\"PUBLIC\"],\n)\n\n")
    with (out_dir / "classpaths.bzl").open("w") as w:
        w.write("# GENERATED by tools/gen-third-party.py via `just lock` -- do not edit.\n")
        w.write("# External artifacts of each gradle configuration, in gradle's classpath order.\n\n")
        w.write("CLASSPATHS = {\n")
        for project in sorted(classpaths):
            w.write(f'    "{project}": {{\n')
            for conf, labels in classpaths[project].items():
                w.write(f'        "{conf}": [\n')
                for l in labels:
                    w.write(f'            "{l}",\n')
                w.write("        ],\n")
            w.write("    },\n")
        w.write("}\n")
    print(f"{len(jars)} artifacts -> {out_dir}/BUCK; {len(classpaths)} projects -> {out_dir}/classpaths.bzl")


if __name__ == "__main__":
    main(*sys.argv[1:3])
